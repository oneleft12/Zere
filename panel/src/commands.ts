/**
 * Каталог команд ZERE — единственный список того, что понимает движок.
 * Показывается на экране «Чат» (`screens/chat.ts`): пользователь видит все
 * команды и вставляет нужную в поле ввода одним нажатием.
 *
 * Источник — обработчики пайплайна (`zere/core/handlers/*` и их C#-порты):
 * MemoryHandler, MemoryQueryHandler, ConversationHandler, ProcessHandler,
 * WindowsHandler, FileHandler, GameHandler, VolumeHandler, DrawingHandler
 * (только Python-редакция) и AIHandler как fallback. Примеры команд —
 * ровно те фразы, которые разбирает движок, поэтому их НЕ переводят через
 * `t()`: локализуются только заголовки и пояснения.
 *
 * Список статический (не из API): `panel/dist` общий для двух редакций,
 * поэтому он работает и со старым бэкендом, которому для нового маршрута
 * требовался бы перезапуск.
 */

export interface CommandItem {
  /** Пример команды в том виде, в каком её понимает движок. */
  command: string;
  /** Что произойдёт; локализуется через t(). */
  hint: string;
}

export interface CommandGroup {
  /** Заголовок группы; локализуется через t(). */
  title: string;
  /** Сноска группы (например, «только Python-редакция»); локализуется. */
  note?: string;
  items: CommandItem[];
}

