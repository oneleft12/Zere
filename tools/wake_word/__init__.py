"""Тулчейн обучения слова-триггера «зере» (wake word).

Пакет обучает крошечный KWS-детектор (keyword spotting) и выпускает ЕДИНЫЙ
ONNX-граф «сырое аудио → вероятность слова». Весь DSP (STFT, мел-фильтры,
лог, нормализация) экспортируется ВНУТРЬ графа, поэтому рантаймы (Python-
редакция `zere/voice/wakeword/` и C#-редакция `ZERE.Voice/WakeWord/`) не
повторяют математику — они просто кормят граф окном 1 с и читают `score`.

Почему своя модель, а не готовый движок: у sherpa-onnx и Vosk нет русских
KWS-моделей, а гонять полный STT на каждые 40 мс — это сотни миллисекунд и
лишняя нагрузка. Крошечная CNN (~55 тыс. параметров, < 1 МБ) считает окно за
единицы миллисекунд на CPU.

Модули:

* :mod:`record_positives` — живые записи слова с микрофона;
* :mod:`synth_positives` — синтез слова локальным Silero TTS с вариациями;
* :mod:`build_negatives` — негативы: свои аудио, MUSAN (по флагу), похожие слова;
* :mod:`data` — реестр датасета, чтение WAV, аугментации на лету;
* :mod:`model` — frontend (log-mel) + CNN и экспорт в ONNX;
* :mod:`train` — обучение, подбор порога, экспорт модели и манифеста;
* :mod:`evaluate` — метрики на held-out (recall, FA/час) и отчёт;
* :mod:`self_test` — смоук всего конвейера на синтетике за < 2 минут.

Запуск любого шага: ``python -m tools.wake_word.<модуль>`` (см. README.md).
"""

